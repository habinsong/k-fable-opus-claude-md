def sinho(m: "re.Match[str]", ctx: Ctx) -> Optional[str]:
    """'문체 신호' -> '문체 특징', '신호로 작용한다' -> '단서가 된다'."""
    gd = m.groupdict()
    if gd.get("target"):
        target = re.sub(r"\s+", " ", gd["target"].strip())
        rep = _SINHO_NOUN_MAP.get(target, target)
        part = gd.get("part")
        if not part:
            return rep
        has_batchim = (ord(rep[-1]) - 0xAC00) % 28 > 0
        if part in ("을", "를"):
            p = "을" if has_batchim else "를"
        elif part in ("이", "가"):
            p = "이" if has_batchim else "가"
        elif part in ("은", "는"):
            p = "은" if has_batchim else "는"
        else:
            p = part
        return rep + p
    raw = m.group("w")
    norm = re.sub(r"\s+", " ", raw.strip())
    return _SINHO_PRED_MAP.get(norm, _SINHO_PRED_MAP.get(raw, "단서가 된다"))


