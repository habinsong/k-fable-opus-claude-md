def deohada(m: "re.Match[str]", ctx: Ctx) -> Optional[str]:
    """'가치를 더하다' -> '가치를 높이다', '깊이를 더한다' -> '더 깊게 한다'."""
    noun = m.group("noun")
    part = m.group("part")
    v = m.group("v")
    table = _DEOHADA_VERBS.get(v, {})
    rep = table.get(noun)
    if rep:
        if rep.startswith("더 "):
            return rep
        return f"{noun}{part} {rep}"
    fallback_map = {
        "더하다": "보태다", "더한다": "보탠다", "더하고": "보태고", "더하며": "보태며",
        "더했다": "보탰다", "더해": "보태", "더하여": "보태어",
    }
    fb = fallback_map.get(v, "보태다")
    return f"{noun}{part} {fb}"


