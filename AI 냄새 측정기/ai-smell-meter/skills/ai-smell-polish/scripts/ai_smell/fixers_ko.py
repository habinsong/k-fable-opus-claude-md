    if gd.get("noun"):
        n = gd["noun"]
        rep = _MILDO_MAP.get(f"{n} 밀도", f"{n} 완성도")
        part = gd.get("part")
        if not part:
            return rep
        has_batchim = (ord(rep[-1]) - 0xAC00) % 28 > 0
        if part in ("을", "를"):
            p = "을" if has_batchim else "를"
        elif part in ("이", "가"):
            p = "이" if has_batchim else "가"
        elif part in ("은", "는"):
            p = "은" if has_batchim else "는"
        else:
            p = part
        return rep + p
    if gd.get("v"):
        v = gd["v"]
        if v.startswith("높이"):
            end = v[2:]
            return "짜임새를 갖추" + end
        return "짜임새가 있다"
    return "짜임새"


